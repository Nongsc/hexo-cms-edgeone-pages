/**
 * EdgeOne Pages / Edge Functions 打包入口。
 *
 * 构建产物为单个 JS 文件，EdgeOne 通过 edgeone.json 的 routes
 * 把 `/api/*` 请求交给这里的 Hono 应用处理。
 *
 * 打包方式：esbuild 将 src/edge.ts 及其依赖（含 @hexo-pro/core）打成
 * 一个 ESM bundle，直接运行在 Edge Functions 的 Node runtime 上。
 */

import { build } from "esbuild";
import { rmSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../..");
const srcDir = resolve(here, "src");
const outDir = resolve(here, "dist-edge");

rmSync(outDir, { recursive: true, force: true });

await build({
  entryPoints: [resolve(srcDir, "edge.ts")],
  outfile: resolve(outDir, "index.js"),
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node20",
  minify: false,
  sourcemap: false,
  absWorkingDir: root,
  // 只把 node: 前缀的内置模块标记为外部；CJS 依赖（gray-matter 等）
  // 由 esbuild 自动转换为 ESM，避免运行期出现 dynamic require。
  external: [
    "node:sqlite",
    "node:crypto",
    "node:fs",
    "node:path",
    "node:url",
    "node:os",
    "node:buffer",
    "node:stream",
    "node:events",
    "node:util"
  ],
  banner: {
    js: [
      "// Generated by apps/api/build-edge.ts — do not edit",
      // CJS 依赖在 ESM 输出中需要 createRequire；这里注入一个基于 import.meta.url 的实现
      'import { createRequire as __createRequire } from "node:module";',
      "const require = __createRequire(import.meta.url);"
    ].join("\n")
  },
  logLevel: "info"
});

console.log("[build-edge] output:", outDir);

