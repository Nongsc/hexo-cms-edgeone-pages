/**
 * EdgeOne Pages · Cloud Functions (Node.js) 打包脚本。
 *
 * 产物：cloud-functions/api/[[default]].js
 *
 * EdgeOne Makers 的路由约定：
 *   - 入口目录为项目根目录的 cloud-functions/
 *   - [[default]].js 是多级动态路由（catch-all），接管 /api/* 全部请求
 *   - 只有导出 Function Handler（onRequest 等）或框架实例的文件才注册为路由，
 *     其他文件视为辅助模块
 *
 * 打包方式：esbuild 将 src/eo.ts 及其依赖（含 @hexo-pro/core）打成单个 ESM bundle。
 * Cloud Functions 的 Node.js runtime 是完整 Node v20 环境，因此 node: 前缀的
 * 内置模块保持 external（运行时由 Node 提供），其余依赖全部打进 bundle。
 */

import { build } from "esbuild";
import { rmSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
// build-edge.ts 位于 apps/api/ 下，here 即 api 目录
const apiDir = here;
const root = resolve(apiDir, "../..");
const outDir = resolve(root, "cloud-functions/api");

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

await build({
  entryPoints: [resolve(apiDir, "src/eo.ts")],
  outfile: resolve(outDir, "[[default]].js"),
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node20",
  minify: false,
  sourcemap: false,
  absWorkingDir: root,
  // Cloud Functions 运行在完整 Node 环境（Node 20）：
  //  - 普通 node:* 内置模块由运行时提供（external）
  //  - node:sqlite 在 Node 20 不存在，且 EdgeOne 会二次打包本 bundle，
  //    遇到 node:sqlite 会报 "Could not resolve sqlite"。因此用 alias 把
  //    node:sqlite 指向 stub（运行时 Node 20 走 sql.js 分支，不会真正调用）。
  //  - sql.js 使用 inline 构建（wasm base64 内联），打进 bundle，无需 external。
  alias: {
    "node:sqlite": resolve(apiDir, "src/node-sqlite-stub.ts")
  },
  external: [
    "node:crypto",
    "node:fs",
    "node:path",
    "node:url",
    "node:os",
    "node:buffer",
    "node:stream",
    "node:events",
    "node:util",
    "node:module"
  ],
  // 注意：banner 注入的标识符必须用独特前缀（__eocms_*），
  // 因 EdgeOne 二次打包会注入自己的 __createRequire 等 shim，重名会报
  // "Identifier '__createRequire' has already been declared"。
  // 同时必须提供全局 require（esbuild 的 __require shim 依赖它处理
  // gray-matter 等 CJS 依赖的 dynamic require）。
  define: {
    __dirname: "__eocms_dirname",
    __filename: "__eocms_filename"
  },
  banner: {
    js: [
      "// Generated by apps/api/build-edge.ts — do not edit",
      'import { createRequire as __eocms_cr } from "node:module";',
      'import { fileURLToPath as __eocms_fileURLToPath } from "node:url";',
      'import { dirname as __eocms_dirnameFn } from "node:path";',
      "const require = __eocms_cr(import.meta.url);",
      "const __eocms_filename = __eocms_fileURLToPath(import.meta.url);",
      "const __eocms_dirname = __eocms_dirnameFn(__eocms_filename);"
    ].join("\n")
  },
  logLevel: "info"
});

console.log("[build-edge] output:", outDir);
