/**
 * EdgeOne Pages · Cloud Functions (Node.js) 打包脚本。
 *
 * 产物：cloud-functions/api/[[default]].js
 *
 * EdgeOne Makers 的路由约定：
 *   - 入口目录为项目根目录的 cloud-functions/
 *   - [[default]].js 是多级动态路由（catch-all），接管 /api/* 全部请求
 *   - 只有导出 Function Handler（onRequest 等）或框架实例的文件才注册为路由，
 *     其他文件视为辅助模块
 *
 * 打包方式：esbuild 将 src/eo.ts 及其依赖（含 @hexo-pro/core）打成单个 ESM bundle。
 * Cloud Functions 的 Node.js runtime 是完整 Node v20 环境，因此 node: 前缀的
 * 内置模块保持 external（运行时由 Node 提供），其余依赖全部打进 bundle。
 */

import { build } from "esbuild";
import { rmSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
// build-edge.ts 位于 apps/api/ 下，here 即 api 目录
const apiDir = here;
const root = resolve(apiDir, "../..");
const outDir = resolve(root, "cloud-functions/api");

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

await build({
  entryPoints: [resolve(apiDir, "src/eo.ts")],
  outfile: resolve(outDir, "[[default]].js"),
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node20",
  minify: false,
  sourcemap: false,
  absWorkingDir: root,
  // Cloud Functions 运行在完整 Node 环境：
  //  - node: 内置模块由运行时提供（external）
  //  - sql.js 使用 inline 构建（wasm 以 base64 内联），需打进 bundle：
  //    部署环境只上传函数目录，若 external 会因找不到 node_modules 而失败。
  external: [
    "node:sqlite",
    "node:crypto",
    "node:fs",
    "node:path",
    "node:url",
    "node:os",
    "node:buffer",
    "node:stream",
    "node:events",
    "node:util",
    "node:module"
  ],
  // sql.js 内部使用 __dirname（CJS 风格）定位资源；本 bundle 为 ESM 且含
  // top-level await，两者共存会让 Node 无法判定模块格式
  // （ERR_AMBIGUOUS_MODULE_SYNTAX）。用 define 将其替换为 ESM 等价写法：
  //   - __dirname      -> import.meta.dirname 的等价表达式
  //   - __filename    -> 当前模块路径
  define: {
    __dirname: "__injected_dirname",
    __filename: "__injected_filename"
  },
  banner: {
    js: [
      "// Generated by apps/api/build-edge.ts — do not edit",
      'import { createRequire as __createRequire } from "node:module";',
      'import { fileURLToPath as __fileURLToPath } from "node:url";',
      'import { dirname as __dirnameFn } from "node:path";',
      "const require = __createRequire(import.meta.url);",
      "const __injected_filename = __fileURLToPath(import.meta.url);",
      "const __injected_dirname = __dirnameFn(__injected_filename);"
    ].join("\n")
  },
  logLevel: "info"
});

console.log("[build-edge] output:", outDir);
